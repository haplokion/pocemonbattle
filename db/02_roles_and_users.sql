-- Создание двух тестовых пользователей БД Oracle для многопользовательского режима
DECLARE
    user_cnt NUMBER;
BEGIN
    -- Пользователь PLAYER1
    SELECT COUNT(*) INTO user_cnt FROM all_users WHERE username = 'PLAYER1';
    IF user_cnt = 0 THEN
        EXECUTE IMMEDIATE 'CREATE USER PLAYER1 IDENTIFIED BY "Player1Password#123" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS';
    END IF;
    EXECUTE IMMEDIATE 'GRANT CREATE SESSION TO PLAYER1';
    EXECUTE IMMEDIATE 'GRANT GAME_PLAYER_ROLE TO PLAYER1';

    -- Пользователь PLAYER2
    SELECT COUNT(*) INTO user_cnt FROM all_users WHERE username = 'PLAYER2';
    IF user_cnt = 0 THEN
        EXECUTE IMMEDIATE 'CREATE USER PLAYER2 IDENTIFIED BY "Player2Password#123" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS';
    END IF;
    EXECUTE IMMEDIATE 'GRANT CREATE SESSION TO PLAYER2';
    EXECUTE IMMEDIATE 'GRANT GAME_PLAYER_ROLE TO PLAYER2';
END;
/
