-- Создание специальной роли для игроков
DECLARE
    role_exists NUMBER;
BEGIN
    SELECT COUNT(*) INTO role_exists FROM dba_roles WHERE role = 'GAME_PLAYER_ROLE';
    IF role_exists = 0 THEN
        EXECUTE IMMEDIATE 'CREATE ROLE GAME_PLAYER_ROLE';
    END IF;
END;
/

-- Предоставление привилегий роли GAME_PLAYER_ROLE
-- Базовые справочники (только чтение)
GRANT SELECT ON ELEMENTS TO GAME_PLAYER_ROLE;
GRANT SELECT ON ELEMENT_ADVANTAGES TO GAME_PLAYER_ROLE;
GRANT SELECT ON CREATURE_TEMPLATES TO GAME_PLAYER_ROLE;
GRANT SELECT ON ITEMS TO GAME_PLAYER_ROLE;

-- Профиль игрока, существа и инвентарь
GRANT SELECT, INSERT, UPDATE ON PLAYERS TO GAME_PLAYER_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE ON PLAYER_CREATURES TO GAME_PLAYER_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE ON PLAYER_INVENTORY TO GAME_PLAYER_ROLE;

-- Игровые сессии и история ходов
GRANT SELECT, INSERT, UPDATE ON BATTLES TO GAME_PLAYER_ROLE;
GRANT SELECT, INSERT, UPDATE ON BATTLE_CREATURES TO GAME_PLAYER_ROLE;
GRANT SELECT, INSERT ON BATTLE_TURNS TO GAME_PLAYER_ROLE;

